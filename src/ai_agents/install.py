def generate_harness_adapters(
    agent_name: str,
    tier_root: Path,
    *,
    tier: str | None = None,
) -> list[dict]:
    """Write pointer files for every harness detected at ``tier_root``.

    ``agent_name`` is the agent's directory name under ``tier_root/agents/``
    — the same name ``install`` was given. It selects the file to write for
    the per-agent harnesses (Claude Code, Cline). The context-file harnesses
    (Gemini CLI, Qwen Code) keep one combined block listing every agent
    installed at the tier, so those are regenerated in full on every call
    regardless of which agent triggered it; that is what keeps the block
    correct after any install.

    ``tier`` is inferred from ``tier_root`` when omitted — see
    ``tier_name_for``.

    Returns one ``{"harness", "path", "action", "reason"}`` dict per detected
    harness, in ``HARNESSES`` order, where ``action`` is ``created``,
    ``updated``, ``unchanged``, or ``skipped``. An empty list means no
    supported harness was detected, which is not an error — it is the normal
    state of a repo that uses none of them.

    Raises ``FileNotFoundError`` if ``agent_name`` is not installed at
    ``tier_root``.
    """
    tier_root = Path(tier_root)
    tier = tier if tier is not None else tier_name_for(tier_root)

    agent = catalog.read_agent(tier_root / "agents" / agent_name)
    if agent is None:
        raise FileNotFoundError(f"agent {agent_name!r} is not installed at {tier_root}")

    results = []
    for harness in detect_harnesses(tier_root, tier):
        # Pointer filenames use the on-disk directory name, not the
        # frontmatter `name:` — the two are the same in practice (the
        # directory name is the fallback), but only one of them is
        # guaranteed to be a safe single path segment.
        path = harness_pointer_path(harness, tier_root, tier, agent_name)

        if harness == "claude-code":
            outcome = _write_pointer_file(path, _render_claude_code(agent, _agent_md_path(tier_root, agent), tier))
        elif harness == "cline":
            outcome = _write_pointer_file(path, _render_cline(agent, _agent_md_path(tier_root, agent), tier))
        else:
            installed = catalog.list_agents(tier_root)
            outcome = _write_managed_block(path, _render_context_block(installed, tier_root, tier))

        results.append({"harness": harness, "path": path, **outcome})

    return results
